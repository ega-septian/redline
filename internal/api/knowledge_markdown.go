var markdownNameClean = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// handleGroupKnowledgeMarkdown: GET /api/groups/{fingerprint}/knowledge.md
// A read-only Markdown page built from stored facts. It never calls an LLM: every section cites the
// run or analysis it came from, so the export can be reviewed like any other piece of evidence.
func (s *Server) handleGroupKnowledgeMarkdown(w http.ResponseWriter, r *http.Request) {
	fingerprint := r.PathValue("fingerprint")
	group, occurrences, err := s.Store.GetGroup(r.Context(), fingerprint)
	if errors.Is(err, store.ErrNotFound) {
		writeError(w, http.StatusNotFound, "kelompok kegagalan tidak ditemukan")
		return
	}
	if err != nil {
		s.serverError(w, err)
		return
	}

	var analysisRecord *store.Analysis
	if record, err := s.Store.GetAnalysis(r.Context(), fingerprint, analysis.PromptVersion); err == nil {
		analysisRecord = &record
	} else if !errors.Is(err, store.ErrNotFound) {
		s.serverError(w, err)
		return
	}

	var knowledge *store.Knowledge
	if fact, err := s.Store.Knowledge(r.Context(), fingerprint); err == nil {
		knowledge = fact
	} else if !errors.Is(err, store.ErrNotFound) {
		s.serverError(w, err)
		return
	}

	experiments, err := s.Store.ListExperiments(r.Context(), fingerprint)
	if err != nil {
		s.serverError(w, err)
		return
	}

	body := renderGroupKnowledgeMarkdown(group, occurrences, analysisRecord, knowledge, experiments, time.Now())
	w.Header().Set("Content-Type", "text/markdown; charset=utf-8")
	w.Header().Set("Content-Disposition", fmt.Sprintf("attachment; filename=%q", markdownFilename(group)))
	w.Header().Set("Cache-Control", "no-store")
	_, _ = w.Write([]byte(body))
}

func renderGroupKnowledgeMarkdown(
	group store.Group,
	occurrences []store.Occurrence,
	analysisRecord *store.Analysis,
	knowledge *store.Knowledge,
	experiments []store.Experiment,
	generatedAt time.Time,
) string {
	var b strings.Builder

	title := firstNonEmpty(group.Title, group.Cause, group.TestKey, group.Fingerprint)
	fmt.Fprintf(&b, "# %s\n\n", mdInline(title))
	fmt.Fprintf(&b, "> Read-only knowledge page generated by Redline on %s. Every section names the run or analysis it came from.\n\n", mdTime(generatedAt))

	b.WriteString("## Test\n\n")
	b.WriteString("| Field | Value |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| Test | %s |\n", mdCode(group.TestKey))
	fmt.Fprintf(&b, "| TC ID | %s |\n", mdCode(group.TestCaseID))
	fmt.Fprintf(&b, "| Project | %s |\n", mdCode(group.Project))
	fmt.Fprintf(&b, "| File | %s |\n", mdCode(group.File))
	fmt.Fprintf(&b, "| Fingerprint | %s |\n", mdCode(group.Fingerprint))
	fmt.Fprintf(&b, "| Status | %s |\n", mdCell(group.Status))
	fmt.Fprintf(&b, "| Occurrences | %d |\n", group.Occurrences)
	fmt.Fprintf(&b, "| Regressions | %d |\n", group.Regressions)
	fmt.Fprintf(&b, "| First seen | %s · run #%d |\n", mdTime(group.FirstSeenAt), group.FirstSeenRun)
	fmt.Fprintf(&b, "| Last seen | %s · run #%d |\n", mdTime(group.LastSeenAt), group.LastSeenRun)
	if group.ResolvedAt != nil {
		fmt.Fprintf(&b, "| Resolved | %s |\n", mdTime(*group.ResolvedAt))
	}
	fmt.Fprintf(&b, "| Triage | %s |\n", mdTriage(group))
	if group.LocalOnly {
		b.WriteString("| Local only | yes, not shown in the team list |\n")
	}
	b.WriteString("\n")

	b.WriteString("## Cause\n\n")
	if analysisRecord != nil {
		fmt.Fprintf(&b, "%s\n\n", mdParagraph(firstNonEmpty(analysisRecord.Summary, group.Summary)))
		fmt.Fprintf(&b, "- Category: **%s**\n", mdInline(analysisRecord.Category))
		fmt.Fprintf(&b, "- Confidence: **%s**\n", mdInline(analysisRecord.Confidence))
		fmt.Fprintf(&b, "- Source: %s", mdInline(analysisRecord.Source))
		if analysisRecord.Model != "" {
			fmt.Fprintf(&b, " · model %s", mdCode(analysisRecord.Model))
		}
		b.WriteString("\n")
		if !analysisRecord.CreatedAt.IsZero() {
			fmt.Fprintf(&b, "- Analyzed: %s\n", mdTime(analysisRecord.CreatedAt))
		}
		if analysisRecord.NextStep != "" {
			fmt.Fprintf(&b, "- Next step: %s\n", mdParagraph(analysisRecord.NextStep))
		}
		if len(analysisRecord.Evidence) > 0 {
			b.WriteString("\n### Evidence\n\n")
			for _, line := range analysisRecord.Evidence {
				fmt.Fprintf(&b, "- %s — source: run #%d\n", mdCode(clipText(line, 500)), group.LastSeenRun)
			}
		}
	} else {
		b.WriteString("No stored analysis yet. The failure is not labeled, proven, or analyzed with AI.\n\n")
		fmt.Fprintf(&b, "- Summary: %s\n", mdParagraph(group.Summary))
		fmt.Fprintf(&b, "- Category: **%s** · confidence **%s**\n", mdInline(firstNonEmpty(group.Category, "unclear")), mdInline(firstNonEmpty(group.Confidence, "none")))
		if group.Cause != "" {
			fmt.Fprintf(&b, "- Stored cause: %s\n", mdInline(group.Cause))
		}
	}
	if group.HumanLabel != "" {
		fmt.Fprintf(&b, "\n**Confirmed by a human:** %s", mdInline(group.HumanLabel))
		if group.HumanNote != "" {
			fmt.Fprintf(&b, " — %s", mdParagraph(group.HumanNote))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n")

	if group.SampleError != "" {
		b.WriteString("## Last error\n\n")
		fmt.Fprintf(&b, "```text\n%s\n```\n\n", mdFence(clipText(group.SampleError, 4000)))
		fmt.Fprintf(&b, "Source: last failure in run #%d.\n\n", group.LastSeenRun)
	}

	b.WriteString("## Run history\n\n")
	if len(occurrences) == 0 {
		b.WriteString("No stored occurrence for this group.\n\n")
	} else {
		b.WriteString("| Run | Date | Status | Branch | Commit | App | Source |\n| --- | --- | --- | --- | --- | --- | --- |\n")
		for _, occurrence := range occurrences {
			fmt.Fprintf(&b, "| #%d | %s | %s | %s | %s | %s | %s |\n",
				occurrence.RunID, mdTime(occurrence.RunCreatedAt), mdCell(occurrence.Status),
				mdCell(occurrence.Branch), mdCode(shortSHA(occurrence.CommitSHA)), mdCell(occurrence.AppVersion),
				mdCell(firstNonEmpty(occurrence.Source, "local")))
		}
		noun := "occurrences"
		if len(occurrences) == 1 {
			noun = "occurrence"
		}
		fmt.Fprintf(&b, "\nLatest %d %s. Each row is a citation for its run id.\n\n", len(occurrences), noun)
	}

	if knowledge != nil {
		b.WriteString("## Knowledge graph\n\n")
		fmt.Fprintf(&b, "From run #%d", knowledge.RunID)
		if knowledge.PassRunID > 0 {
			fmt.Fprintf(&b, ", compared with the last passing run #%d", knowledge.PassRunID)
		} else {
			b.WriteString(", no last passing run")
		}
		b.WriteString(".\n\n")

		if len(knowledge.Files) == 0 && len(knowledge.Endpoints) == 0 {
			b.WriteString("No file or endpoint facts stored for this run.\n\n")
		}
		if len(knowledge.Files) > 0 {
			b.WriteString("### Files\n\n")
			for i, file := range knowledge.Files {
				if i >= 20 {
					fmt.Fprintf(&b, "- … %d more files\n", len(knowledge.Files)-20)
					break
				}
				state := "unchanged"
				if file.Changed {
					state = "changed since the last pass"
				}
				direct := "indirect"
				if file.Direct {
					direct = "direct"
				}
				fmt.Fprintf(&b, "- %s — %s, %s; other tests: %s\n", mdCode(file.Path), direct, state, mdSplit(file.Others))
			}
			b.WriteString("\n")
		}
		if len(knowledge.Endpoints) > 0 {
			b.WriteString("### Endpoints\n\n")
			for i, endpoint := range knowledge.Endpoints {
				if i >= 20 {
					fmt.Fprintf(&b, "- … %d more endpoints\n", len(knowledge.Endpoints)-20)
					break
				}
				seen := "not seen passing before"
				if endpoint.SeenPassing {
					seen = "seen passing before"
				}
				fmt.Fprintf(&b, "- %s — %s; failed with changed files: %s; failed without them: %s\n",
					mdCode(endpoint.Key), seen, mdSplit(endpoint.WithChanged), mdSplit(endpoint.Without))
			}
			b.WriteString("\n")
		}
	}

	if len(experiments) > 0 {
		b.WriteString("## Proof\n\n")
		for i, experiment := range experiments {
			if i >= 5 {
				fmt.Fprintf(&b, "- … %d older experiments\n", len(experiments)-5)
				break
			}
			fmt.Fprintf(&b, "- **%s** · %s · %d/%d passing runs", mdInline(experiment.Kind), mdInline(experiment.Outcome), experiment.Passes, experiment.Runs)
			if experiment.Hypothesis != "" {
				fmt.Fprintf(&b, " — %s", mdParagraph(experiment.Hypothesis))
			}
			if !experiment.CreatedAt.IsZero() {
				fmt.Fprintf(&b, " (%s)", mdTime(experiment.CreatedAt))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## Sources\n\n")
	fmt.Fprintf(&b, "- Failure group and occurrences: %s\n", mdCode(fmt.Sprintf("GET /api/groups/%s", group.Fingerprint)))
	if len(occurrences) > 0 {
		runs := make([]string, 0, len(occurrences))
		for _, occurrence := range occurrences {
			runs = append(runs, fmt.Sprintf("#%d", occurrence.RunID))
		}
		fmt.Fprintf(&b, "- Runs cited: %s\n", strings.Join(runs, ", "))
	}
	if analysisRecord != nil {
		fmt.Fprintf(&b, "- Cause: %s analysis for this group", mdCode(analysisRecord.Source))
		if !analysisRecord.CreatedAt.IsZero() {
			fmt.Fprintf(&b, ", created %s", mdTime(analysisRecord.CreatedAt))
		}
		b.WriteString("\n")
	}
	if knowledge != nil {
		fmt.Fprintf(&b, "- Graph facts: run #%d", knowledge.RunID)
		if knowledge.PassRunID > 0 {
			fmt.Fprintf(&b, " compared with pass run #%d", knowledge.PassRunID)
		}
		b.WriteString("\n")
	}
	if len(experiments) > 0 {
		fmt.Fprintf(&b, "- Proof: %d stored experiment(s) for this group\n", len(experiments))
	}
	fmt.Fprintf(&b, "- Generated at: %s\n", mdTime(generatedAt))

	return b.String()
}

func markdownFilename(group store.Group) string {
	name := firstNonEmpty(group.TestCaseID, group.Fingerprint, "group")
	if len(name) > 60 {
		name = name[:60]
	}
	name = strings.Trim(markdownNameClean.ReplaceAllString(name, "-"), "-_.")
	if name == "" {
		name = "group"
	}
	return "redline-" + name + ".md"
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if strings.TrimSpace(value) != "" {
			return value
		}
	}
	return ""
}

func mdInline(value string) string {
	value = strings.TrimSpace(strings.ReplaceAll(value, "`", "'"))
	value = strings.Join(strings.Fields(value), " ")
	if value == "" {
		return "—"
	}
	return value
}

func mdParagraph(value string) string {
	value = strings.TrimSpace(strings.ReplaceAll(value, "`", "'"))
	if value == "" {
		return "—"
	}
	return value
}

func mdCode(value string) string {
	value = mdInline(value)
	if value == "—" {
		return "—"
	}
	return "`" + value + "`"
}

func mdCell(value string) string {
	value = mdInline(value)
	return strings.ReplaceAll(value, "|", "\\|")
}

func mdFence(value string) string {
	value = strings.TrimSpace(value)
	value = strings.ReplaceAll(value, "```", "'''")
	if value == "" {
		return "—"
	}
	return value
}

func mdTime(value time.Time) string {
	if value.IsZero() {
		return "—"
	}
	return value.UTC().Format("2006-01-02 15:04 UTC")
}

func mdTriage(group store.Group) string {
	status := firstNonEmpty(group.TriageStatus, "open")
	parts := []string{mdCell(status)}
	if group.TriageOwner != "" {
		parts = append(parts, "owner "+mdCode(group.TriageOwner))
	}
	if group.TriageNote != "" {
		parts = append(parts, mdCell(group.TriageNote))
	}
	return strings.Join(parts, " · ")
}

func mdSplit(split store.TestSplit) string {
	parts := make([]string, 0, 2)
	if len(split.Failed) > 0 {
		parts = append(parts, fmt.Sprintf("%d failed", len(split.Failed)))
	}
	if len(split.Passed) > 0 {
		parts = append(parts, fmt.Sprintf("%d passed", len(split.Passed)))
	}
	if len(parts) == 0 {
		return "no other test"
	}
	return strings.Join(parts, ", ")
}

func shortSHA(value string) string {
	if len(value) > 7 {
		return value[:7]
	}
	return value
}
